
package list;

import java.util.Vector;

public class VectorExample {

    public static void main(String[] args) {

        // Creating a Vector
        Vector<String> fruits = new Vector<>();

        // add(): adding elements
        fruits.add("Apple");
        fruits.add("Banana");
        fruits.add("Mango");
        fruits.add("Orange");

        System.out.println("Original Vector: " + fruits);


    }
}

